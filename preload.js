const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  games: () => ipcRenderer.invoke('games'),
  rescan: () => ipcRenderer.invoke('rescan'),
  cover: item => ipcRenderer.invoke('cover', item),
  launch: item => ipcRenderer.invoke('launch', item),
  cancelLaunch: () => ipcRenderer.invoke('cancelLaunch'),
  add: () => ipcRenderer.invoke('add'),
  addFolder: () => ipcRenderer.invoke('addFolder'),
  folders: () => ipcRenderer.invoke('folders'),
  removeFolder: p => ipcRenderer.invoke('removeFolder', p),
  remove: id => ipcRenderer.invoke('remove', id),
  setCover: id => ipcRenderer.invoke('setCover', id),
  hdInfo: id => ipcRenderer.invoke('hdInfo', id),
  hdOptions: id => ipcRenderer.invoke('hdOptions', id),
  hdApply: (id, i) => ipcRenderer.invoke('hdApply', id, i),
  hdDone: () => ipcRenderer.invoke('hdDone'),
  onNote: cb => ipcRenderer.on('note', (e, m) => cb(m)),
  pickPlaces: id => ipcRenderer.invoke('pickPlaces', id),
  pickList: dir => ipcRenderer.invoke('pickList', dir),
  pickThumb: f => ipcRenderer.invoke('pickThumb', f),
  pickApply: (id, f) => ipcRenderer.invoke('pickApply', id, f),
  chooseVideo: () => ipcRenderer.invoke('chooseVideo'),
  useVideo: () => ipcRenderer.invoke('useVideo'),
  getCfg: () => ipcRenderer.invoke('getCfg'),
  setCfg: p => ipcRenderer.invoke('setCfg', p),
  gpuInfo: () => ipcRenderer.invoke('gpuInfo'),
  tuneState: () => ipcRenderer.invoke('tuneState'),
  perf: p => ipcRenderer.invoke('perf', p),
  retune: () => ipcRenderer.invoke('retune'),
  hide: () => ipcRenderer.invoke('hide'),
  quit: () => ipcRenderer.invoke('quit'),
  onEnter: cb => ipcRenderer.on('enter', cb),
  onLeave: cb => ipcRenderer.on('leave', cb),
  onPause: cb => ipcRenderer.on('pause', cb),
  onResume: cb => ipcRenderer.on('resume', cb),
  onCover: cb => ipcRenderer.on('cover', (e, c) => cb(c)),
  onLaunchEnd: cb => ipcRenderer.on('launch-end', () => cb()),
  onLibrary: cb => ipcRenderer.on('library', () => cb()),
  updCheck: () => ipcRenderer.invoke('updCheck'),
  updInstall: () => ipcRenderer.invoke('updInstall'),
  onUpdAvailable: cb => ipcRenderer.on('upd-available', (e, v) => cb(v)),
  onUpdProgress: cb => ipcRenderer.on('upd-progress', (e, p) => cb(p)),
  onStats: cb => ipcRenderer.on('stats', (e, s) => cb(s))
});
